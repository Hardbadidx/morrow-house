/**
 * Retrieve a dish by its ID / URL slug
 */
export function getDishById(id) {
  if (!id) return null;
  const normalized = id.toLowerCase().trim();
  if (normalized === SIGNATURE_DISH.id) {
    return SIGNATURE_DISH;
  }
  return MENU_ITEMS.find((dish) => dish.id === normalized) || null;
}
